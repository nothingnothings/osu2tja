def get_section_name(s):
    if s is None:
        return ""
    if s.startswith('[') and s.endswith(']'):
        return s[1:-1]
    return ""


def get_var(s):
    if s is None:
        return "", ""
    try:
        idx = s.index(':')
        var_name = s[:idx].strip()
        var_value = s[idx+1:].strip()
    except:
        return "", ""
    return var_name, var_value


def get_timing_point(s, prev_timing_point=None):
    if s is None:
        return {}

    ps = s.split(',')
    if len(ps) < 8:
        return {}

    offset, rawbpmv, beats, _, _, _, _, is_ggt = ps[:8]
    is_ggt = (is_ggt != '0')

    ret = {}
    try:
        ret["offset"] = int(offset)
        if float(rawbpmv) > 0:
            bpm = ret["bpm"] = 60 * 1000.0 / float(rawbpmv)
            ret["scroll"] = 1.0
            ret["redline"] = True
        elif float(rawbpmv) < 0:
            ret["bpm"] = prev_timing_point.get("bpm", None)
            ret["scroll"] = -100.0 / float(rawbpmv)
            ret["redline"] = False
            ret["offset"] = get_real_offset(ret["offset"])
        else:
            assert False
        ret["beats"] = int(beats)
        ret["GGT"] = is_ggt
    except:
        print("Osu file Error, at [TimingPoints] section, please check")
        return {}

    return ret


