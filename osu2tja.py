def write_incomplete_bar(tm, bar_data, begin, end, tja_contents):
    if len(bar_data) == 0 and int(begin) == int(end):
        return

    if len(bar_data) == 0:
        tja_contents.append(make_cmd(FMT_DELAY, (end - begin) / 1000.0))
        return

    tpb = T_MINUTE / tm["bpm"]
    my_beat_cnt = 1.0 * (end - begin) * tm["bpm"] / T_MINUTE
    min_beat_cnt = get_real_beat_cnt(
        tm, 1.0 * tm["bpm"] * (bar_data[-1][1] - begin) / T_MINUTE) + 1.0 / T_GRID

    global guess_measure
    if not guess_measure:
        for beat_cnt, m_num, m_den in measure_table:
            # the span must fit before the next timing point exactly, or the
            # leftover overshoot silently shifts everything after it
            if beat_cnt >= min_beat_cnt and \
                    begin + 1.0 * beat_cnt * tpb <= end:
                tja_contents.append(make_cmd(FMT_MEASURECHANGE, m_num, m_den))
                write_bar_data(tm, bar_data, begin, begin + beat_cnt * tpb, tja_contents)
                # the delay must be measured from the exact bar span, or a
                # fraction of a millisecond is gained at every BPM change
                delay_time = end - (begin + 1.0 * beat_cnt * tpb)
                if delay_time > 1e-3:
                    tja_contents.append(make_cmd(FMT_DELAY, delay_time / 1000.0))
                return

    denominator = 48 * 48
    # a TJA "#MEASURE n/d" bar lasts 4*n/d beats, so the fraction must be
    # scaled by 1/4 or the bar plays four times longer than intended
    numerator = int(round(denominator * min_beat_cnt / 4.0))
    _gcd = gcd(denominator, numerator)
    denominator /= _gcd
    numerator /= _gcd

    if denominator in (1, 2):
        fix_mul = 4 / denominator
        denominator *= fix_mul
        numerator *= fix_mul

    tja_contents.append("//[Warning] This may be erronous!!")
    tja_contents.append(make_cmd(FMT_MEASURECHANGE, int(numerator), int(denominator)))
    write_bar_data(tm, bar_data, begin, begin + min_beat_cnt * tpb, tja_contents)
    delay_time = end - (begin + 1.0 * min_beat_cnt * tpb)
    if delay_time > 1e-3:
        tja_contents.append(make_cmd(FMT_DELAY, delay_time / 1000.0))
    return


def write_bar_data(tm, bar_data, begin, end, tja_contents):
    global show_head_info
    global combo_cnt, tail_fix
    global commands_within

    t_unit = 60.0 * 1000 / tm["bpm"] / T_GRID
    offset_list = [int(begin)] + [datum[1] for datum in bar_data] + [int(end)]
    delta_list = []
    for offset1, offset2 in zip(offset_list[:-1], offset_list[1:]):
        delta = (offset2 - offset1) / t_unit
        t_unit_cnt = int(round(delta))
        delta_list.append(t_unit_cnt)

    if abs(delta_list[-1]) < 1:
        tail_fix = True
        write_bar_data(tm, bar_data[:-1], begin, end, tja_contents)
        return

    ret_str = ""
    if len(bar_data) == 0:
        offset = begin
        while commands_within and int(offset) >= int(commands_within[0][0]):
            ret_str += "\n" + make_cmd(*commands_within[0][1:]) + "\n"
            commands_within = commands_within[1:]

    delta_gcd = gcd_of_list(delta_list)
    ret_str += "0" * int(delta_list[0] / delta_gcd)
    empty_t_unit = ["0" * int(x / delta_gcd - 1) for x in delta_list[1:]]

    for empty_t_unit_cnt, (note, offset) in zip(empty_t_unit, bar_data):
        while commands_within and int(offset) >= int(commands_within[0][0]):
            ret_str += "\n" + make_cmd(*commands_within[0][1:]) + "\n"
            commands_within = commands_within[1:]
        ret_str += note + empty_t_unit_cnt

    head = "%4d %6d %.2f %2d " % (combo_cnt, format_time(int(begin)), delta_gcd / float(T_GRID), len(ret_str))
    if show_head_info:
        ret_str = head + ret_str

    tja_contents.append(ret_str + ',')

    for note, offset in bar_data:
        if note in (ONP_DON, ONP_KATSU, ONP_DON_DAI, ONP_KATSU_DAI):
            combo_cnt += 1


# difficulty tiers, in ascending order
COURSE_NAMES = ('Easy', 'Normal', 'Hard', 'Oni', 'Edit')
COURSE_ORDER = {name: i for i, name in enumerate(COURSE_NAMES)}
# plausible star range for each tier, used to clamp the estimated level
COURSE_LEVEL_RANGE = {
    'Easy': (1, 4),
    'Normal': (3, 6),
    'Hard': (5, 8),
    'Oni': (6, 10),
    'Edit': (8, 10),
}

# notes per second -> base star level, linearly interpolated between points
_LEVEL_TABLE = (
    (0.8, 1.0), (1.3, 2.0), (2.0, 3.0), (2.7, 4.0), (3.5, 5.0),
    (4.4, 6.0), (5.4, 7.0), (6.6, 8.0), (8.0, 9.0), (9.6, 10.0),
)


def _density_to_level(nps):
    if nps <= _LEVEL_TABLE[0][0]:
        return _LEVEL_TABLE[0][1]
    for (d0, l0), (d1, l1) in zip(_LEVEL_TABLE[:-1], _LEVEL_TABLE[1:]):
        if nps <= d1:
            return l0 + (l1 - l0) * (nps - d0) / (d1 - d0)
    return _LEVEL_TABLE[-1][1]


def estimate_level(hitobjects):
    # star level estimated from note density: mostly the average density,
    # with a smaller weight on the peak density over a 2 second window
    # (a 1 second window overrates short bursts on TV size songs)
    offsets = sorted(off for note, off in hitobjects
                     if note in (ONP_DON, ONP_KATSU, ONP_DON_DAI, ONP_KATSU_DAI))
    if not offsets:
        return 1

    duration = (offsets[-1] - offsets[0]) / 1000.0
    avg_nps = len(offsets) / duration if duration > 0 else len(offsets)

    peak_nps = 0
    left = 0
    for right, off in enumerate(offsets):
        while off - offsets[left] > 2000:
            left += 1
        peak_nps = max(peak_nps, (right - left + 1) / 2.0)

    level = 0.7 * _density_to_level(avg_nps) + 0.3 * _density_to_level(peak_nps)
    return int(min(10, max(1, level + 0.5)))


def infer_course_and_level(version_str, hitobjects):
    v = (version_str or '').lower()
    level = estimate_level(hitobjects)
    named = True

    # tier keywords; the order matters (ura/inner/hell oni must beat plain oni)
    if re.search(r'ura\s*oni|uraoni|\bura\b|inner\s*oni|inneroni|\binner\b'
                 r'|hell\s*oni|\bextra\b|\bmaster\b', v):
        course = 'Edit'
    elif 'kantan' in v or 'beginner' in v:
        course = 'Easy'
    elif 'futsu' in v:
        course = 'Normal'
    elif 'muzukashi' in v:
        course = 'Hard'
    elif re.search(r'\beasy\b', v):
        course = 'Easy'
    elif re.search(r'\bnormal\b', v):
        course = 'Normal'
    elif re.search(r'\bhard\b', v):
        course = 'Hard'
    elif re.search(r'\binsane\b|\bexpert\b', v):
        course = 'Oni'
    elif re.search(r'oni\b', v):
        course = 'Oni'
    else:
        # no known tier name: estimate the tier from note density
        named = False
        if level <= 4:
            course = 'Easy'
        elif level <= 6:
            course = 'Normal'
        elif level <= 7:
            course = 'Hard'
        else:
            course = 'Oni'

    lo, hi = COURSE_LEVEL_RANGE[course]
    level = int(min(hi, max(lo, level)))
    return course, level, named


def osu2tja(fp, audio_name):
    global slider_velocity, timingpoints
    global balloons, tail_fix, ignore_format_ver
    global osu_format_ver
    global commands_within
    global taiko_mode

    tja_contents = list()

    audio = ""
    title = ""
    subtitle = ""
    creator = ""
    artist = ""
    version = ""
    preview = 0
    hitobjects = []

    osu_ver_str = ""
    curr_sec = ""
    lines = fp.readlines()
    for line in lines:
        line = line.strip()
        if line == "":
            continue

        if osu_ver_str == "":
            osu_ver_str = line
            try:
                osu_format_ver_pos = line.index(OSU_VER_STR_PREFIX) + len(OSU_VER_STR_PREFIX)
                osu_format_ver = int(osu_ver_str[osu_format_ver_pos:])
            except:
                osu_format_ver = 10
            if not ignore_format_ver:
                if osu_format_ver not in OSU_VER_SUPPORT:
                    print(f"Warning: format v{osu_format_ver} might not be fully supported.")

        new_sec = get_section_name(line)
        if new_sec:
            curr_sec = new_sec
            continue

        vname, vval = get_var(line)

        if curr_sec == "General":
            if vname == "AudioFilename":
                audio = vval
            elif vname == "PreviewTime":
                preview = int(vval)
            elif vname == "Mode":
                taiko_mode = (int(vval) == 1)

        elif curr_sec == "Metadata":
            if vname in ("Title", "TitleUnicode"):
                title = vval or title
            elif vname == "Creator":
                creator = vval
            elif vname == "Version":
                version = vval
            elif vname == "Source":
                subtitle = vval
            elif vname in ("Artist", "ArtistUnicode"):
                artist = vval or artist
        elif curr_sec == "Difficulty":
            if vname == "SliderMultiplier":
                slider_velocity = float(vval)
        elif curr_sec == "TimingPoints":
            prev_timing_point = timingpoints and timingpoints[-1] or None
            data = get_timing_point(line, prev_timing_point)
            if data:
                timingpoints.append(data)
        elif curr_sec == "HitObjects":
            data = get_note(line)
            if data:
                hitobjects.extend(data)

    if not hitobjects:
        return None

    # drop duplicate notes snapped onto the same grid slot (keep the first)
    note_chars = (ONP_DON, ONP_KATSU, ONP_DON_DAI, ONP_KATSU_DAI)
    deduped = []
    for note, offset in hitobjects:
        if note in note_chars and deduped and deduped[-1][0] in note_chars \
                and abs(deduped[-1][1] - offset) < 1e-6:
            continue
        deduped.append((note, offset))
    hitobjects = deduped

    if int(hitobjects[0][1]) < timingpoints[0]["offset"]:
        new_tm_first = dict(timingpoints[0])
        new_tm_first["offset"] = int(hitobjects[0][1])
        timingpoints = [new_tm_first] + timingpoints

    cur_scroll = 1.0
    cur_ggt = False
    for tm in timingpoints:
        if tm["scroll"] != cur_scroll:
            commands_within.append((tm["offset"], FMT_SCROLLCHANGE, tm["scroll"]))
        if tm["GGT"] != cur_ggt:
            commands_within.append((tm["offset"], tm["GGT"] and FMT_GOGOSTART or FMT_GOGOEND))
        cur_scroll = tm["scroll"]
        cur_ggt = tm["GGT"]

    BPM = timingpoints[0]["bpm"]
    tm_idx = 0
    obj_idx = 0
    measure = timingpoints[0]["beats"]
    curr_bpm = BPM

    bar_data = []
    bar_offset_begin = timingpoints[0]["offset"]
    bar_max_length = 1.0 * measure * T_MINUTE / curr_bpm
    time_per_beat = T_MINUTE / curr_bpm

    bar_cnt = 1
    course, level, course_named = infer_course_and_level(version, hitobjects)

    def is_new_measure(timing_point):
        # only red lines (real timing points) are measure boundaries;
        # inherited points only change scroll speed or gogo, which are
        # emitted inside the bars through commands_within instead
        return timing_point["redline"]

    while obj_idx < len(hitobjects):
        next_obj = hitobjects[obj_idx]
        next_obj_offset = int(next_obj[1])

        if tm_idx < len(timingpoints):
            next_measure_offset = timingpoints[tm_idx]["offset"]
        else:
            next_measure_offset = bar_offset_begin + bar_max_length + 1

        if tm_idx < len(timingpoints) and not is_new_measure(timingpoints[tm_idx]):
            tm_idx += 1
            continue

        tpb = T_MINUTE / curr_bpm
        end = min(bar_offset_begin + bar_max_length, next_measure_offset)

        if next_obj_offset + tpb / T_GRID >= int(end):
            if int(end) == int(bar_offset_begin + bar_max_length):
                tm = get_base_timing_point(timingpoints, bar_offset_begin)
                write_bar_data(tm, bar_data, bar_offset_begin, end, tja_contents)
                bar_data = []
                bar_cnt += 1
                bar_offset_begin = get_real_offset(end)
                bar_max_length = measure * time_per_beat
            elif int(end) == next_measure_offset:
                write_incomplete_bar(get_base_timing_point(timingpoints, bar_offset_begin),
                                     bar_data, bar_offset_begin, end, tja_contents)
                bar_data = []
                measure = timingpoints[tm_idx]["beats"]
                if timingpoints[tm_idx]["redline"]:
                    curr_bpm = timingpoints[tm_idx]["bpm"]
                    bar_offset_begin = next_measure_offset
                    tja_contents.append(make_cmd(FMT_BPMCHANGE, curr_bpm))
                else:
                    bar_offset_begin = end
                time_per_beat = (60 * 1000) / curr_bpm
                bar_max_length = measure * time_per_beat

                if tail_fix:
                    tail_fix = False
                    obj_idx -= 1
                    new_obj = (hitobjects[obj_idx][0], bar_offset_begin)
                    hitobjects[obj_idx] = new_obj

                tja_contents.append(make_cmd(FMT_MEASURECHANGE, measure, 4))
                tm_idx += 1
            else:
                assert False, "BAR END POS ERROR"
        else:
            if next_obj[1] < bar_offset_begin:
                bar_data.append((next_obj[0], bar_offset_begin))
            else:
                bar_data.append(next_obj)
            obj_idx += 1

    if len(bar_data) > 0:
        write_bar_data(get_base_timing_point(timingpoints, bar_offset_begin),
                       bar_data, bar_offset_begin, end, tja_contents)

    # negative offsets mean the audio starts after beat 0, so the sign of
    # the TJA OFFSET must simply be the opposite of the first timing point
    return {
        "title": title,
        "subtitle": subtitle,
        "artist": artist,
        "creator": creator,
        "audio": audio or audio_name,
        "preview": preview,
        "bpm": timingpoints[0]["bpm"],
        "offset_ms": timingpoints[0]["offset"],
        "course": course,
        "level": level,
        "course_named": course_named,
        "balloons": balloons,
        "contents": tja_contents,
        "version": version,
        "taiko_mode": taiko_mode,
    }


def sanitize_filename(name):
    name = re.sub(r'[<>:"/\\|?*\x00-\x1f]', '_', name).strip().rstrip('.')
    return name or "Unknown"


def assign_unique_courses(charts):
    # OpenTaiko can only show one chart per course, so every chart needs its
    # own course slot. Charts whose tier was named explicitly keep priority
    # over charts whose tier was only estimated from note density.
    used = set()
    order = sorted(charts, key=lambda c: (not c["course_named"],
                                          COURSE_ORDER[c["course"]], c["level"]))
    for c in order:
        want = COURSE_ORDER[c["course"]]
        slot = None
        # try the desired course first, then nearby free ones
        for i in list(range(want, min(want + 3, len(COURSE_NAMES)))) + \
                list(range(want - 1, max(want - 2, -1), -1)):
            if i not in used:
                slot = i
                break
        if slot is None:
            c["skipped"] = "no free course slot (already used by a similar difficulty)"
            continue
        used.add(slot)
        c["course"] = COURSE_NAMES[slot]

    kept = [c for c in order if "skipped" not in c]
    kept.sort(key=lambda c: COURSE_ORDER[c["course"]])
    skipped = [c for c in order if "skipped" in c]
    return kept, skipped


def write_merged_tja(tja_path, charts):
    # all difficulties of the song are merged into a single .tja file,
    # one COURSE section each, which is how OpenTaiko shows difficulty tiers
    base = charts[0]
    bpm_str = format_bpm(base["bpm"])
    offset_str = "%.3f" % (-base["offset_ms"] / 1000.0)

    lines = []
    lines.append("TITLE:%s" % base["title"])
    lines.append("SUBTITLE:%s" % (base["subtitle"] or base["artist"]))
    lines.append("WAVE:%s" % base["audio"])
    lines.append("BPM:%s" % bpm_str)
    lines.append("OFFSET:%s" % offset_str)
    lines.append("DEMOSTART:%.3f" % (max(0, base["preview"]) / 1000.0))
    if base["creator"]:
        lines.append("MAKER:%s" % base["creator"])
    if base.get("bgmovie"):
        lines.append("BGMOVIE:%s" % base["bgmovie"])

    for c in charts:
        lines.append("")
        lines.append("COURSE:%s" % c["course"])
        lines.append("LEVEL:%d" % c["level"])
        lines.append("BALLOON:%s" % ",".join(str(b) for b in c["balloons"]))
        # per-course timing, in case a difficulty is timed differently
        c_bpm = format_bpm(c["bpm"])
        c_offset = "%.3f" % (-c["offset_ms"] / 1000.0)
        if c_bpm != bpm_str:
            lines.append("BPM:%s" % c_bpm)
        if c_offset != offset_str:
            lines.append("OFFSET:%s" % c_offset)
        lines.append("")
        lines.append("#START")
        lines.extend(c["contents"])
        lines.append("#END")

    lines.append(WATER_MARK)
    with open(tja_path, 'w', encoding='utf-8') as tja_fp:
        tja_fp.write("\n".join(lines) + "\n")


def process_osz_files(include_all=False):
    output_dir = Path("osu-tracks")
    output_dir.mkdir(parents=True, exist_ok=True)

    local_dir = Path(".")
    osz_files = list(local_dir.rglob("*.osz"))

    if not osz_files:
        print("No .osz files found in the local folder.")
        return

    print(f"Found {len(osz_files)} .osz file(s). Processing...")
    video_extensions = ('.mp4', '.avi', '.flv', '.wmv', '.mkv')

    for osz_path in osz_files:
        print(f"Processing: {osz_path.name}")
        try:
            with zipfile.ZipFile(osz_path, 'r') as zf:
                extract_path = output_dir / osz_path.stem
                extract_path.mkdir(parents=True, exist_ok=True)
                zf.extractall(extract_path)

                # remove .tja files from earlier runs so old outputs
                # don't show up in OpenTaiko next to the new merged one
                for old_tja in extract_path.rglob("*.tja"):
                    old_tja.unlink()

                # Scan for background movie files in the song directory
                bg_movie = ""
                for file in extract_path.iterdir():
                    if file.suffix.lower() in video_extensions:
                        bg_movie = file.name
                        break

                charts = []
                for osu_file in sorted(extract_path.rglob("*.osu")):
                    reset_global_variables()
                    try:
                        with open(osu_file, 'r', encoding='utf-8-sig', errors='ignore') as fp:
                            chart = osu2tja(fp, audio_name="audio.mp3")
                        if chart is None:
                            continue
                        chart["bgmovie"] = bg_movie
                        charts.append(chart)
                    except Exception as e:
                        print(f"  -> Error converting {osu_file.name}: {e}")

                if not charts:
                    print("  -> No convertible difficulties found, skipped")
                    continue

                # charts made for osu!taiko convert much better than regular
                # osu! difficulties, so prefer them when both exist
                taiko_charts = [c for c in charts if c["taiko_mode"]]
                if taiko_charts and len(taiko_charts) < len(charts) and not include_all:
                    for c in charts:
                        if not c["taiko_mode"]:
                            print(f"  -> Skipped non-taiko difficulty [{c['version']}]"
                                  f" (run with --all to include it)")
                    charts = taiko_charts

                charts, skipped = assign_unique_courses(charts)
                for c in skipped:
                    print(f"  -> Skipped difficulty [{c['version']}]: {c['skipped']}")
                if not charts:
                    continue

                if len(set(c["audio"] for c in charts)) > 1:
                    print("  -> Warning: difficulties use different audio files;"
                          " only the first one is referenced")

                title = charts[0]["title"] or osz_path.stem
                tja_filename = "%s.tja" % sanitize_filename(title)
                tja_path = extract_path / tja_filename
                write_merged_tja(tja_path, charts)

                summary = ", ".join("%s %d*" % (c["course"], c["level"]) for c in charts)
                print(f"  -> Converted: {tja_filename} ({summary})")
        except Exception as e:
            print(f"Error reading {osz_path.name}: {e}")

    print("All processing complete!")


